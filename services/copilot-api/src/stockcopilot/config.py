from __future__ import annotations

from datetime import date
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Runtime configuration, read from environment variables (or a local `.env`)."""

    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")

    # Data source: the Road2Tech v2 CSV folder, or a PostgreSQL database loaded from it.
    data_backend: Literal["csv", "postgres"] = "csv"
    dataset_dir: Path = Field(
        default=Path("../../public/softtek/dataset/dataset-hackathon-road2tech/v2"),
        description="Folder with the v2 CSV files (generated by scripts/dataset/run_all.py at the repo root).",
    )
    database_url: str | None = Field(default=None, description="postgresql://user:pass@host:5432/db")

    # The dataset ends on 2026-09-30. The demo "today" sits two weeks earlier so the forecast
    # horizon still has calendar and weather context. Leave empty to use the last day of data.
    demo_as_of: date | None = date(2026, 9, 16)

    # LLM: Gemini through the Google AI Studio API key. Without a key the agent runs in
    # offline mode (rule-based intent parsing + templated summaries) so the demo still works.
    google_api_key: str | None = None
    gemini_model: str = "gemini-3.8-flash"
    gemini_temperature: float = 0.2
    llm_mode: Literal["auto", "gemini", "offline"] = "auto"

    # Forecast source: deterministic fallback, local CatBoost JSONL, or published DynamoDB batch.
    forecast_provider: Literal["local", "jsonl", "dynamodb"] = "local"
    forecast_file: Path | None = None
    forecast_table_name: str | None = None
    aws_region: str | None = None

    # Persistence for LangGraph checkpoints (needed for approvals that resume later).
    checkpointer: Literal["memory", "postgres"] = "memory"

    cors_origins: list[str] = ["http://localhost:3000"]

    @property
    def use_gemini(self) -> bool:
        if self.llm_mode == "offline":
            return False
        if self.llm_mode == "gemini":
            return True
        return bool(self.google_api_key)


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    return Settings()
